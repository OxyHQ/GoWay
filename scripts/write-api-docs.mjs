/** Every operation, in document order, with its tag. */
function operationsOf(document) {
  const operations = [];
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    for (const method of METHODS) {
      const operation = item?.[method];
      if (!operation) continue;
      if (typeof operation.operationId !== 'string' || operation.operationId === '') {
        throw new Error(`${method.toUpperCase()} ${path} has no operationId`);
      }
      operations.push({ method, path, operation, tag: operation.tags?.[0] ?? 'Other' });
    }
  }
  return operations;
}

function authOf(operation) {
  const security = operation.security;
  if (!Array.isArray(security) || security.length === 0) return 'None. No session is read.';
  const anonymous = security.some((entry) => isObject(entry) && Object.keys(entry).length === 0);
  return anonymous
    ? 'Optional. Answers without a session; a valid Oxy session may widen what is returned.'
    : 'Required. A valid Oxy session (`Authorization: Bearer <token>`), or `401 unauthorized`.';
}

/** A tag's section heading. `Search API`, not `Search`: the `search` operation owns that anchor. */
function tagHeading(tag) {
  return `${tag} API`;
}

function jsonSchemaOf(content) {
  return content?.['application/json']?.schema;
}

/** The schema names a JSON schema references, directly. */
function directRefs(schema, into = new Set()) {
  if (Array.isArray(schema)) {
    for (const entry of schema) directRefs(entry, into);
  } else if (isObject(schema)) {
    if (typeof schema.$ref === 'string') into.add(refName(schema.$ref));
    for (const value of Object.values(schema)) directRefs(value, into);
  }
  return into;
}

/** The error codes of a non-2xx response, as `openapi.ts` writes them into its description. */
function errorCodesOf(response) {
  // `openapi.ts` writes `<status text>: \`code\`, \`code\``; the status text may
  // itself quote a header (`Retry-After`), so only what follows the last `: `
  // is the code list.
  const description = String(response?.description ?? '');
  const list = description.slice(description.lastIndexOf(': ') + 2);
  return [...list.matchAll(/`([a-z_]+)`/g)].map((match) => match[1]);
}

function parameterRows(operation, linked) {
  const lines = ['| Name | In | Required | Type | Notes |', '| --- | --- | --- | --- | --- |'];
  for (const parameter of operation.parameters ?? []) {
    const extra = [];
    if (parameter.style === 'form' && parameter.explode === false) {
      extra.push('Comma-separated list, sent once (`a,b,c`)');
    }
    const notes = [parameter.description, notesOf(parameter.schema, extra)]
      .filter(Boolean)
      .join('. ');
    lines.push(
      `| ${cell(code(parameter.name))} | ${parameter.in} | ${parameter.required ? 'yes' : 'no'} | ${cell(typeOf(parameter.schema, linked))} | ${cell(notes)} |`,
    );
  }
  return lines;
}

/** `PlacePage` → `a page of Place`, when the schema is a list page. */
function pageNote(name, components, linked) {
  const schema = components[name];
  const items = schema?.properties?.items;
  if (!hasProperties(schema) || !schema.properties.nextCursor || items?.type !== 'array') return '';
  return `: a page of ${typeOf(items.items, linked)} (\`{ items, nextCursor }\`)`;
}

function renderOperation(entry, components, linked) {
  const { method, path, operation } = entry;
  const lines = [`### ${operation.operationId}`, '', `\`${method.toUpperCase()} ${path}\``, ''];

  if (typeof operation.summary === 'string' && operation.summary !== operation.operationId) {
    lines.push(operation.summary, '');
  }
  if (typeof operation.description === 'string' && operation.description !== '') {
    lines.push(operation.description, '');
  }

  lines.push(`**Authentication:** ${authOf(operation)}`, '');

  if ((operation.parameters ?? []).length > 0) {
    lines.push('**Parameters**', '', ...parameterRows(operation, linked), '');
  }

  const bodySchema = jsonSchemaOf(operation.requestBody?.content);
  if (bodySchema !== undefined) {
    const required = operation.requestBody?.required ? 'required' : 'optional';
    if (bodySchema.$ref !== undefined) {
      const name = refName(bodySchema.$ref);
      lines.push(`**Request body** (\`application/json\`, ${required}): ${code(name)}`, '');
      lines.push(...schemaBody(components[name], linked), '');
    } else {
      lines.push(`**Request body** (\`application/json\`, ${required})`, '');
      lines.push(...schemaBody(bodySchema, linked), '');
    }
  }

  const responses = Object.entries(operation.responses ?? {});
  const successes = responses.filter(([status]) => /^2\d\d$/.test(status));
  lines.push('**Success response**', '');
  for (const [status, response] of successes) {
    const schema = jsonSchemaOf(response?.content);
    if (schema === undefined) {
      lines.push(`- \`${status}\`: no content.`);
    } else if (schema.$ref !== undefined) {
      const name = refName(schema.$ref);
      lines.push(
        `- \`${status}\`: ${schemaLink(name, linked)}${pageNote(name, components, linked)}.`,
      );
    } else {
      lines.push(`- \`${status}\`: ${typeOf(schema, linked)}.`);
    }
  }
  lines.push('');

  const failures = responses.filter(([status]) => !/^2\d\d$/.test(status));
  if (failures.length > 0) {
    lines.push('**Errors**', '', '| Status | Codes |', '| --- | --- |');
    for (const [status, response] of failures) {
      const codes = errorCodesOf(response);
      if (codes.length === 0) {
        throw new Error(
          `${method.toUpperCase()} ${path} ${status}: no error code in ${JSON.stringify(response?.description)}`,
        );
      }
      lines.push(`| \`${status}\` | ${codes.map((value) => code(value)).join(', ')} |`);
    }
    lines.push('');
  }

  return lines;
}

