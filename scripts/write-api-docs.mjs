#!/usr/bin/env bun

// Write `docs/developers/api/operations.md`, the HTTP API operation reference,
// from the committed OpenAPI document `packages/contracts/openapi.json`.
//
//   bun ./scripts/write-api-docs.mjs           write the page
//   bun ./scripts/write-api-docs.mjs --check   exit 1 if the page on disk is stale
//
// Run it after `bun run openapi` whenever a contract changes, and commit both.
//
// The OpenAPI document is itself generated from `API_OPERATIONS` and the zod
// contracts (`scripts/write-openapi.mjs`) and held fresh by
// `scripts/check-openapi-fresh.mjs`, so this script reads the JSON and nothing
// else: it imports no TypeScript and needs no installed dependencies, which is
// why it runs under plain `node` as well as `bun`.
//
// The output is deterministic: tags and operations keep the document's order
// (the registry's order), schemas are sorted by name, and nothing depends on the
// clock or the machine. The rendering is exported and pure so it can be tested
// without touching the file system; the CLI half only does the I/O.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

/** How deep inline objects are expanded into dotted field rows. */
const MAX_FIELD_DEPTH = 3;

const SCHEMA_REF_PREFIX = '#/components/schemas/';

const HEADER = '<!-- generated by scripts/write-api-docs.mjs; do not edit -->';

// ---------------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------------

/** GitHub's heading slug: lower case, punctuation dropped, spaces to dashes. */
export function slugOf(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

/** Text safe inside a Markdown table cell. */
function cell(text) {
  return String(text).replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}

/** Inline code, safe for values that contain a backtick. */
function code(value) {
  const text = String(value);
  return text.includes('`') ? `\`\` ${text} \`\`` : `\`${text}\``;
}

function refName(ref) {
  if (typeof ref !== 'string' || !ref.startsWith(SCHEMA_REF_PREFIX)) {
    throw new Error(`unsupported $ref ${JSON.stringify(ref)}`);
  }
  return ref.slice(SCHEMA_REF_PREFIX.length);
}

function schemaLink(name, linked) {
  return linked.has(name) ? `[${code(name)}](#${slugOf(name)})` : code(name);
}

function isObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

/** `{ anyOf: [X, { type: 'null' }] }` → `{ schema: X, nullable: true }`. */
function unwrapNullable(schema) {
  const union = schema?.anyOf ?? schema?.oneOf;
  if (Array.isArray(union) && union.length === 2) {
    const nonNull = union.filter((entry) => entry?.type !== 'null');
    if (nonNull.length === 1) return { schema: nonNull[0], nullable: true };
  }
  return { schema, nullable: false };
}

/** An inline object with named properties, which is expanded into rows. */
function hasProperties(schema) {
  return isObject(schema) && isObject(schema.properties) && schema.$ref === undefined;
}

// ---------------------------------------------------------------------------
// Describing one schema: its type and its constraints
// ---------------------------------------------------------------------------

/** Whether {@link typeOf} spells this schema as several alternatives. */
function isUnion(schema) {
  if (!isObject(schema) || schema.$ref !== undefined || schema.const !== undefined) return false;
  if (Array.isArray(schema.enum)) return false;
  const union = schema.anyOf ?? schema.oneOf;
  if (Array.isArray(union)) return union.length > 1;
  return Array.isArray(schema.allOf) || (Array.isArray(schema.type) && schema.type.length > 1);
}

/** A short, human type for a schema, linking named schemas. */
export function typeOf(schema, linked) {
  if (
    schema === true ||
    schema === undefined ||
    (isObject(schema) && Object.keys(schema).length === 0)
  )
    return 'any';
  if (schema === false) return 'nothing';
  if (schema.$ref !== undefined) return schemaLink(refName(schema.$ref), linked);
  if (schema.const !== undefined) return code(JSON.stringify(schema.const));
  if (Array.isArray(schema.enum)) {
    return `one of ${schema.enum.map((value) => code(JSON.stringify(value))).join(', ')}`;
  }
  const union = schema.anyOf ?? schema.oneOf;
  if (Array.isArray(union)) {
    const parts = [];
    for (const entry of union) {
      const part = typeOf(entry, linked);
      if (!parts.includes(part)) parts.push(part);
    }
    return parts.join(' or ');
  }
  if (Array.isArray(schema.allOf))
    return schema.allOf.map((entry) => typeOf(entry, linked)).join(' and ');
  if (Array.isArray(schema.type))
    return schema.type.map((type) => typeOf({ ...schema, type }, linked)).join(' or ');
  switch (schema.type) {
    case 'array':
      if (Array.isArray(schema.prefixItems)) {
        return `[${schema.prefixItems.map((entry) => typeOf(entry, linked)).join(', ')}]`;
      }
      {
        // `array of (A or B)`, never `array of A or B`, which reads as two types.
        const inner = typeOf(schema.items, linked);
        return isUnion(schema.items) ? `array of (${inner})` : `array of ${inner}`;
      }
    case 'object':
      if (!hasProperties(schema) && isObject(schema.additionalProperties)) {
        return `map of string to ${typeOf(schema.additionalProperties, linked)}`;
      }
      return 'object';
    case 'string':
      return schema.format ? `string (${schema.format})` : 'string';
    case 'integer':
    case 'number':
    case 'boolean':
    case 'null':
      return schema.type;
    default:
      return 'any';
  }
}

/**
 * The constraints a schema states, in words. A list's items are described
 * after `[]`, their items after `[][]`, as field paths spell them.
 */
export function constraintsOf(schema, level = '') {
  if (!isObject(schema)) return [];
  const notes = [];
  const range = (low, high, unit) => {
    // `1 character`, `2 characters`: the unit agrees with the number it follows.
    const of = (value) => (unit === '' ? '' : ` ${value === 1 ? unit : `${unit}s`}`);
    if (low !== undefined && low === high) notes.push(`exactly ${low}${of(low)}`);
    else if (low !== undefined && high !== undefined) notes.push(`${low} to ${high}${of(high)}`);
    else if (low !== undefined) notes.push(`at least ${low}${of(low)}`);
    else if (high !== undefined) notes.push(`at most ${high}${of(high)}`);
  };
  // zod spells "any integer" as the safe-integer range; that bound is no constraint.
  const bound = (value) => (Math.abs(value) === Number.MAX_SAFE_INTEGER ? undefined : value);
  const maximum = bound(schema.maximum);
  if (schema.exclusiveMinimum !== undefined && maximum !== undefined) {
    notes.push(`greater than ${schema.exclusiveMinimum}, at most ${maximum}`);
  } else if (schema.exclusiveMinimum !== undefined) {
    notes.push(`greater than ${schema.exclusiveMinimum}`);
  } else {
    range(bound(schema.minimum), maximum, '');
  }
  if (schema.exclusiveMaximum !== undefined) notes.push(`less than ${schema.exclusiveMaximum}`);
  range(schema.minLength, schema.maxLength, 'character');
  // A tuple's length is its type (`[number, number]`), not a constraint to restate.
  if (!Array.isArray(schema.prefixItems)) range(schema.minItems, schema.maxItems, 'item');
  if (typeof schema.pattern === 'string') notes.push(`pattern ${code(schema.pattern)}`);
  if (schema.default !== undefined) notes.push(`default ${code(JSON.stringify(schema.default))}`);
  const own = level === '' ? notes : notes.length > 0 ? [`${code(level)} ${notes.join(', ')}`] : [];
  if (schema.type === 'array' && isObject(schema.items) && !Array.isArray(schema.prefixItems)) {
    own.push(...constraintsOf(schema.items, `${level}[]`));
  }
  return own;
}

function notesOf(schema, extra = []) {
  const parts = [];
  if (isObject(schema) && typeof schema.description === 'string') parts.push(schema.description);
  parts.push(...extra);
  const constraints = constraintsOf(schema);
  if (constraints.length > 0) parts.push(constraints.join('; '));
  return parts.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('. ');
}

// ---------------------------------------------------------------------------
// Field tables
// ---------------------------------------------------------------------------

/** One row per field, inline objects expanded as `parent.child` and `list[].child`. */
function fieldRows(schema, linked, prefix = '', depth = 0) {
  const rows = [];
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  for (const [name, raw] of Object.entries(schema.properties ?? {})) {
    const { schema: field, nullable } = unwrapNullable(raw);
    const path = `${prefix}${name}`;
    const type = typeOf(raw, linked);
    rows.push({
      name: path,
      type,
      required: required.has(name),
      notes: notesOf(field, nullable && !type.endsWith('or null') ? ['May be null'] : []),
    });
    if (depth + 1 >= MAX_FIELD_DEPTH) continue;
    if (hasProperties(field)) {
      rows.push(...fieldRows(field, linked, `${path}.`, depth + 1));
    } else if (field?.type === 'array' && hasProperties(field.items)) {
      rows.push(...fieldRows(field.items, linked, `${path}[].`, depth + 1));
    }
  }
  return rows;
}

function fieldTable(rows) {
  if (rows.length === 0) return ['No fields.'];
  const lines = ['| Field | Type | Required | Notes |', '| --- | --- | --- | --- |'];
  for (const row of rows) {
    lines.push(
      `| ${cell(code(row.name))} | ${cell(row.type)} | ${row.required ? 'yes' : 'no'} | ${cell(row.notes)} |`,
    );
  }
  return lines;
}

/** A variant's label: its `const` discriminator, when it has one. */
function variantLabel(variant, index) {
  for (const [name, property] of Object.entries(variant?.properties ?? {})) {
    if (property?.const !== undefined)
      return `${code(name)} = ${code(JSON.stringify(property.const))}`;
  }
  return `Variant ${index + 1}`;
}

/** The body of a schema's description: a field table, or one per variant. */
function schemaBody(schema, linked) {
  const lines = [];
  if (isObject(schema) && typeof schema.description === 'string')
    lines.push(schema.description, '');
  if (hasProperties(schema)) {
    lines.push(...fieldTable(fieldRows(schema, linked)));
    return lines;
  }
  const union = schema?.oneOf ?? schema?.anyOf;
  if (Array.isArray(union) && union.some((variant) => hasProperties(variant))) {
    lines.push('One of:', '');
    union.forEach((variant, index) => {
      if (hasProperties(variant)) {
        lines.push(`- ${variantLabel(variant, index)}:`, '');
        lines.push(...fieldTable(fieldRows(variant, linked)).map((line) => `  ${line}`), '');
      } else {
        lines.push(`- ${typeOf(variant, linked)}`, '');
      }
    });
    while (lines.at(-1) === '') lines.pop();
    return lines;
  }
  lines.push(`Type: ${typeOf(schema, linked)}.`);
  const constraints = constraintsOf(schema);
  if (constraints.length > 0) lines.push('', `Constraints: ${constraints.join('; ')}.`);
  return lines;
}

