// The page
// ---------------------------------------------------------------------------

/** The Markdown for `docs/developers/api/operations.md`. Pure. */
export function renderApiOperations(document) {
  if (!isObject(document) || !isObject(document.paths)) {
    throw new Error('not an OpenAPI document: no `paths`');
  }
  const components = document.components?.schemas ?? {};
  const operations = operationsOf(document);
  if (operations.length === 0) throw new Error('the OpenAPI document describes no operations');

  // The schemas the reference section describes: everything a response
  // reaches, plus anything a request body names beyond its own root (which is
  // described in place, under its operation).
  const bodyRoots = new Set();
  const seeds = new Set();
  for (const { operation } of operations) {
    const body = jsonSchemaOf(operation.requestBody?.content);
    if (body?.$ref !== undefined) {
      const name = refName(body.$ref);
      bodyRoots.add(name);
      for (const inner of directRefs(components[name])) seeds.add(inner);
    } else if (body !== undefined) {
      for (const inner of directRefs(body)) seeds.add(inner);
    }
    for (const parameter of operation.parameters ?? []) {
      for (const inner of directRefs(parameter.schema)) seeds.add(inner);
    }
    for (const [status, response] of Object.entries(operation.responses ?? {})) {
      // Every error answers the shared envelope, described in the README.
      if (!/^2\d\d$/.test(status)) continue;
      for (const inner of directRefs(jsonSchemaOf(response?.content))) seeds.add(inner);
    }
  }
  const linked = new Set();
  const queue = [...seeds];
  while (queue.length > 0) {
    const name = queue.shift();
    if (linked.has(name)) continue;
    if (!(name in components)) throw new Error(`$ref to missing schema ${name}`);
    linked.add(name);
    for (const inner of directRefs(components[name])) if (!linked.has(inner)) queue.push(inner);
  }
  const schemaNames = [...linked].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

  // Tags in the document's declared order, then any an operation names beyond it.
  const tags = [];
  for (const tag of document.tags ?? [])
    if (tag?.name && !tags.includes(tag.name)) tags.push(tag.name);
  for (const { tag } of operations) if (!tags.includes(tag)) tags.push(tag);
  const byTag = new Map(tags.map((tag) => [tag, operations.filter((entry) => entry.tag === tag)]));

  // Every heading's anchor must be unique, or a link lands on the wrong one.
  const anchors = new Map();
  const claim = (heading) => {
    const slug = slugOf(heading);
    if (anchors.has(slug)) {
      throw new Error(`heading "${heading}" has the same anchor as "${anchors.get(slug)}"`);
    }
    anchors.set(slug, heading);
    return slug;
  };
  for (const heading of ['API operations', 'Contents', 'Schemas']) claim(heading);
  for (const tag of tags) claim(tagHeading(tag));
  for (const { operation } of operations) claim(operation.operationId);
  for (const name of schemaNames) claim(name);

  const server = document.servers?.[0]?.url;
  const lines = [
    HEADER,
    '',
    '# API operations',
    '',
    `Every operation of the ${document.info?.title ?? 'GoWay API'} (version ${document.info?.version ?? '?'}), ` +
      'generated from the OpenAPI document in `packages/contracts/openapi.json`. ' +
      (server ? `Paths are relative to the base URL \`${server}\`. ` : '') +
      'Authentication, errors, pagination and the other conventions every operation follows are in the ' +
      '[API overview](README.md).',
    '',
    '## Contents',
    '',
  ];
  for (const tag of tags) {
    const count = byTag.get(tag).length;
    lines.push(
      `- [${tagHeading(tag)}](#${slugOf(tagHeading(tag))}) (${count} operation${count === 1 ? '' : 's'})`,
    );
  }
  lines.push(`- [Schemas](#schemas) (${schemaNames.length})`, '');

  for (const tag of tags) {
    const entries = byTag.get(tag);
    lines.push(
      `## ${tagHeading(tag)}`,
      '',
      '| Operation | Method and path | Authentication |',
      '| --- | --- | --- |',
    );
    for (const { method, path, operation } of entries) {
      const auth = authOf(operation).split('.')[0];
      lines.push(
        `| [${operation.operationId}](#${slugOf(operation.operationId)}) | \`${method.toUpperCase()} ${path}\` | ${auth} |`,
      );
    }
    lines.push('');
    for (const entry of entries) lines.push(...renderOperation(entry, components, linked));
  }

  lines.push(
    '## Schemas',
    '',
    'The objects the operations above answer with, by name. Request bodies are described under their operation. ' +
      'Nested objects are expanded as `parent.child`, and objects inside a list as `list[].child`, ' +
      `to ${MAX_FIELD_DEPTH} levels.`,
    '',
  );
  for (const name of schemaNames) {
    if (bodyRoots.has(name) && !seeds.has(name)) continue;
    lines.push(`### ${name}`, '', ...schemaBody(components[name], linked), '');
  }

  while (lines.at(-1) === '') lines.pop();
  return `${lines.join('\n')}\n`;
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

const isMain =
  import.meta.main ??
  (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url));

if (isMain) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const source = resolve(root, 'packages', 'contracts', 'openapi.json');
  const target = resolve(root, 'docs', 'developers', 'api', 'operations.md');
  const shown = relative(root, target);

  const generated = renderApiOperations(JSON.parse(readFileSync(source, 'utf8')));

  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current !== generated) {
      console.error(
        `::error::${shown} is ${current === null ? 'MISSING' : 'STALE'}: ` +
          'packages/contracts/openapi.json generates a different page. ' +
          'Run `bun ./scripts/write-api-docs.mjs` and commit the result.',
      );
      process.exit(1);
    }
    console.log(`${shown} is fresh: it is exactly what packages/contracts/openapi.json generates.`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, generated);
    console.log(`wrote ${target}`);
  }
}
