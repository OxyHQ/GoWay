/**
 * `bun run --cwd packages/backend live:areas` — derive every live source's
 * areas from its operator's own stops (`areas.ts`) and rewrite
 * `areas.generated.ts`. Run it when a source is added or its network changes;
 * `areas.test.ts` fails for a source with stops and no areas.
 *
 * Reads, per source: the static GTFS's `stops.txt` (the shapes where a
 * portal publishes no stops), or a bike share's GBFS stations. Nothing else
 * is fetched, and nothing about anyone is.
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { LIVE_POLICY } from '../config/live';
import { areasOf, type SourceAreas } from './areas';
import { LIVE_SOURCES } from './catalogue';
import { parseCsv } from './staticGtfs';
import type { LiveSourceDefinition } from './types';
import { readZipEntries } from './zip';

type Point = readonly [number, number];

const headers = { 'user-agent': LIVE_POLICY.userAgent };

async function bytes(url: string): Promise<Uint8Array> {
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(300_000) });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return new Uint8Array(await response.arrayBuffer());
}

function pointsOfCsv(text: string, latitude: string, longitude: string): Point[] {
  const { header, rows } = parseCsv(text);
  const la = header.indexOf(latitude);
  const lo = header.indexOf(longitude);
  if (la < 0 || lo < 0) return [];
  return rows.map((row) => [Number(row[la]), Number(row[lo])] as const);
}

async function gtfsPoints(definition: LiveSourceDefinition): Promise<Point[]> {
  const location = definition.staticGtfs;
  if (!location) return [];
  const decoder = new TextDecoder();
  if ('routes' in location) {
    return pointsOfCsv(
      decoder.decode(await bytes(location.shapes)),
      'shape_pt_lat',
      'shape_pt_lon',
    );
  }
  const zips = 'zip' in location ? [location.zip] : location.zips;
  const points: Point[] = [];
  for (const url of zips) {
    const entries = readZipEntries(await bytes(url), ['stops.txt', 'shapes.txt']);
    const stops = entries.get('stops.txt');
    const shapes = entries.get('shapes.txt');
    if (stops) points.push(...pointsOfCsv(decoder.decode(stops), 'stop_lat', 'stop_lon'));
    else if (shapes)
      points.push(...pointsOfCsv(decoder.decode(shapes), 'shape_pt_lat', 'shape_pt_lon'));
  }
  return points;
}

async function gbfsPoints(definition: LiveSourceDefinition): Promise<Point[]> {
  const json = async (url: string) =>
    JSON.parse(new TextDecoder().decode(await bytes(url))) as Record<string, unknown>;
  const discovery = (await json(definition.defaultUrl)).data as Record<
    string,
    { feeds?: { name: string; url: string }[] }
  >;
  const feeds = Object.values(discovery)[0]?.feeds ?? [];
  const information = feeds.find((feed) => feed.name === 'station_information');
  if (!information) return [];
  const stations = ((await json(information.url)).data as { stations?: unknown[] }).stations ?? [];
  return stations.map((station) => {
    const { lat, lon } = station as { lat: number; lon: number };
    return [lat, lon] as const;
  });
}

async function main(): Promise<void> {
  const out: Record<string, SourceAreas> = {};
  for (const definition of LIVE_SOURCES) {
    const points =
      definition.kind === 'bikeshare' ? await gbfsPoints(definition) : await gtfsPoints(definition);
    const areas = areasOf(points);
    if (!areas) {
      console.log(`${definition.id}: no stops known — keeps its coverage box`);
      continue;
    }
    out[definition.id] = areas;
    console.log(`${definition.id}: ${points.length} points → ${areas.areas.length} areas`);
  }
  // `__dirname`: this package compiles to CommonJS (`db/migrationsFolder.ts`).
  const target = join(__dirname, 'areas.generated.ts');
  writeFileSync(
    target,
    `// Generated by \`bun run --cwd packages/backend live:areas\` (\`runAreas.ts\`): do not edit.\n` +
      `import type { SourceAreas } from './areas';\n\n` +
      `export const LIVE_SOURCE_AREAS: Readonly<Record<string, SourceAreas>> = ${JSON.stringify(out, null, 2)};\n`,
  );
  console.log(`wrote ${target}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
