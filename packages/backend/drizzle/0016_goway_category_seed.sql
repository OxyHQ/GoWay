CREATE FUNCTION "places_categories_taxonomy_guard"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  previous text[] := '{}';
  refused text;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    previous := OLD."categories";
  END IF;
  SELECT candidate INTO refused
  FROM unnest(NEW."categories") AS candidate
  WHERE (candidate IS NULL OR candidate <> ALL (previous))
    AND NOT EXISTS (
      SELECT 1 FROM "place_categories" AS category
      WHERE category."key" = candidate AND category."status" = 'active'
    )
  LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'places.categories: % is not an active place category', coalesce(refused, 'NULL')
      USING ERRCODE = 'check_violation', CONSTRAINT = 'places_categories_taxonomy_guard',
            TABLE = 'places', COLUMN = 'categories';
  END IF;
  RETURN NEW;
END
$$;
