CREATE FUNCTION "place_categories_english_label_guard"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  subject text;
BEGIN
  IF TG_TABLE_NAME = 'place_categories' THEN
    subject := NEW."key";
  ELSE
    subject := OLD."category_key";
  END IF;
  IF EXISTS (SELECT 1 FROM "place_categories" WHERE "key" = subject)
     AND NOT EXISTS (
       SELECT 1 FROM "place_category_labels" WHERE "category_key" = subject AND "language" = 'en'
     ) THEN
    RAISE EXCEPTION 'place category % has no English label', subject
      USING ERRCODE = 'check_violation', CONSTRAINT = 'place_categories_english_label',
            TABLE = TG_TABLE_NAME;
  END IF;
  RETURN NULL;
END
$$;
