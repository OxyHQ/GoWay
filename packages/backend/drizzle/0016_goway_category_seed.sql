-- Custom SQL migration: the category taxonomy as data, and what holds
-- `places.categories` to it once `0017` drops the static CHECK.
--
-- PRE, like `0015`: the previous image writes only keys of the registry this
-- seed is generated from, so every trigger below accepts everything it writes.
--
-- 1. The seed: the 148 categories of the 0.3.0 registry with their glyphs and
--    OpenStreetMap tags, and their labels in twelve languages (`en`, `ar`,
--    `bn`, `ca`, `de`, `es`, `fr`, `hi`, `ja`, `pt-BR`, `ru`, `zh-Hans`) —
--    1,776 rows, GENERATED from the registry and from the label translations
--    (`i18n/category-labels.json`, whose English and Spanish are the
--    registry's), nothing retyped. Positions are each category's place among
--    its siblings, in tens. The seed is a migration, not a moderator's write,
--    and records no `place_category_events`.
-- 2. English is required: a deferred constraint trigger refuses, at commit, a
--    category without an `en` label — whether the category arrived without one
--    or its `en` row was deleted or moved to another language.
-- 3. Keys are immutable, and a key a place carries is never deleted.
-- 4. `places.categories` holds active categories: an INSERT, or an UPDATE that
--    ADDS a key, is refused unless every added key is an `active` category. A
--    key the row already carried may stay (a deprecated category never makes a
--    place uneditable) and existing rows are never re-checked: what `0013`'s
--    CHECK validated stays valid, and a deprecated key stays readable.
--
-- Lock order: everything up to (4) touches only the new tables. (4) takes
-- SHARE ROW EXCLUSIVE on `places` (writes wait, reads do not) and `0017`
-- ACCESS EXCLUSIVE (everything waits) for milliseconds, until the phase
-- commits. `lock_timeout` makes a long-running statement on `places` fail this
-- phase instead of queueing every read behind it; the deploy is then re-run.
-- It is `SET LOCAL`, so it lasts for the phase's one transaction — `0017`
-- included — and no longer.
